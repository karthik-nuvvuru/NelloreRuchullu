export const getMenuItemsByRestaurant = (restaurantId: string) =>
  menuItems.filter((item) => item.restaurantId === restaurantId);

export const getMenuItemsByCategory = (category: string) =>
  menuItems.filter((item) => item.category.toLowerCase() === category.toLowerCase());

export const searchMenuItems = (query: string) => {
  const lower = query.toLowerCase();
  return menuItems.filter(
    (item) =>
      item.name.toLowerCase().includes(lower) ||
      item.description.toLowerCase().includes(lower) ||
      item.category.toLowerCase().includes(lower)
  );
};

export const getPopularItems = () => menuItems.filter((item) => item.popular);
